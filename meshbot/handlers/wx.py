def render_unbekannt(arg: str) -> str:
    """The place is not in the directory.

    Costs the same airtime as the old refusal `WX: <place> unbekannt`, but also
    says how to do it right — otherwise it would be mockery without use.
    """
    ort = " ".join(arg.split())[:20] or "Nix"
    key = normalisiere(ort)
    if key in SPEZIAL:
        return "WX: " + SPEZIAL[key]
    # A real place, just the wrong one. That deserves a different answer than a
    # typo: someone typing "Hamburg" did not mistype anything.
    if key in AUSSERHALB:
        return f"WX: {ort.title()} liegt ned in Kaernten. 34 Stationen, alle da"
    # Choose on the normalised form, otherwise "villagh" gets a different answer
    # than "Villagh" — the same typo should stay the same typo.
    return "WX: " + SPOTT[sum(key.encode()) % len(SPOTT)].format(ort=ort.title())


def render(ort: str, werte: dict[str, Any], stale: bool = False,
           station: str | None = None, geraten: bool = False,
           anzeige: str | None = None) -> str:
    """One line, fixed order: temperature, humidity, wind, pressure.

    If the station sits somewhere other than the place asked for, it is named.
    Nobody measures in Knappenberg — the values come from Friesach, and that has
    to be stated, or somebody takes it for a measurement on their doorstep.

    `geraten` appends a question mark to the place name. One character, and the
    answer stops claiming to know: `WX Villach?: 21C` reads as "I assume you
    mean Villach". Before this, a guessed answer was indistinguishable from a
    known one.
    """
    marker = "~" if stale else ""
    # `anzeige` is the original spelling from OSM ("Nötsch im Gailtal"), the key
    # is the umlaut-free lookup form. If it is missing -- old file, or name and
    # key are identical anyway -- the key will do.
    kopf = (anzeige or ort.title()) + ("?" if geraten else "")
    if station and normalisiere(station) != normalisiere(anzeige or ort):
        kopf = f"{kopf} ({station})"
    teile = [f"WX {kopf}: {marker}"]
    if werte.get("TL") is not None:
        teile.append(f"{werte['TL']:.1f}C")
    if werte.get("RF") is not None:
        teile.append(f"{werte['RF']:.0f}%")
    if werte.get("FFAM") is not None:
        kmh = werte["FFAM"] * 3.6
        teile.append(f"Wind {kmh:.0f}km/h {_richtung(werte.get('DD'))}".strip())
    if werte.get("P") is not None:
        teile.append(f"{werte['P']:.0f}hPa")
    return teile[0] + ", ".join(teile[1:])
